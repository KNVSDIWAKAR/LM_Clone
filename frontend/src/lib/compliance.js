// Helpers for the `compliance_checks` array attached to every decision.

export const allChecksPass = (checks) => checks.length === 0 || checks.every((c) => c.verdict === "pass");
export const hasFlagOrWarning = (checks) => checks.some((c) => c.verdict === "flagged" || c.verdict === "warning");
export const hasFlag = (checks) => checks.some((c) => c.verdict === "flagged");

export function verdictFill(verdict) {
  if (verdict === "pass") return "hsl(142, 71%, 45%)";
  if (verdict === "flagged") return "hsl(0, 84%, 60%)";
  return "hsl(38, 92%, 50%)";
}

export function verdictStroke(verdict) {
  if (verdict === "pass") return "hsl(142, 71%, 35%)";
  if (verdict === "flagged") return "hsl(0, 84%, 45%)";
  return "hsl(38, 92%, 40%)";
}

/** Plain-language rationale shown above the checks on the decision detail page. */
export function buildRationale(decision, checks) {
  const lines = [];
  const flagged = checks.filter((c) => c.verdict === "flagged");
  const warnings = checks.filter((c) => c.verdict === "warning");
  const passed = checks.filter((c) => c.verdict === "pass");

  if (flagged.length > 0) {
    lines.push(
      `The agent flagged ${flagged.length} check${flagged.length === 1 ? "" : "s"} that fall outside policy, which is why this decision was routed for human review.`,
    );
  } else if (warnings.length > 0) {
    lines.push(
      `All hard checks passed, but ${warnings.length} item${warnings.length === 1 ? "" : "s"} warrant a second look before this is finalized.`,
    );
  } else if (checks.length > 0) {
    lines.push("Every compliance check passed; this decision is presented for confirmation and audit.");
  }

  for (const c of [...flagged, ...warnings].slice(0, 4)) lines.push(`${c.name}: ${c.detail}`);

  if (passed.length > 0 && (flagged.length > 0 || warnings.length > 0)) {
    lines.push(`${passed.length} other check${passed.length === 1 ? "" : "s"} passed without issue.`);
  }
  if (lines.length === 0) {
    lines.push(
      decision.description ||
        "Decision generated by the automated agent pipeline; review the description and checks below.",
    );
  }
  return lines;
}
